def fs(v):
    """Fraction → 式の文字列（mathlib の書き方）"""
    v = Fr(v)
    if v.denominator == 1:
        return str(v.numerator)
    return ("-" if v < 0 else "") + "{" + str(abs(v.numerator)) + "|" + str(v.denominator) + "}"


def hirei_shiki(a):
    a = Fr(a)
    if a == 1:
        return "y=x"
    if a == -1:
        return "y=-x"
    return f"y={fs(a)}x"


def hanpi_shiki(a):
    a = Fr(a)
    return f"y=-{{{abs(a.numerator)}|x}}" if a < 0 else f"y={{{a.numerator}|x}}"


def table(xs, ys=None):
    h = "".join(f"<td>{t(str(v))}</td>" for v in xs)
    b = "".join(f"<td>{t(fs(v)) if ys is not None else ''}</td>" for v in (ys if ys is not None else xs))
    return f"<table class=tb><tr><th>{t('x')}</th>{h}</tr><tr><th>{t('y')}</th>{b}</tr></table>"


def tvals(f, xs):
    return ", ".join(t(fs(f(x))) for x in xs)


